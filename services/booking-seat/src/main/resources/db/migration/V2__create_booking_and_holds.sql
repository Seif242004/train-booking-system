-- Slice 7: bookings and holds (SRS sections 4.2, 5 and 8).

-- A booking, from the hold (PENDING_PAYMENT) to its end. The user is the Keycloak subject as a plain value, never a foreign
-- key (CLAUDE.md); the e-mail and name are copied from the token so that tickets and e-mails need no user table.
CREATE TABLE booking (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    reference          VARCHAR2(20 CHAR)  NOT NULL,            -- what the passenger quotes to support, for example TB-7K2M9Q
    user_id            VARCHAR2(64 CHAR)  NOT NULL,            -- Keycloak sub
    user_email         VARCHAR2(254 CHAR),
    user_name          VARCHAR2(200 CHAR),
    trip_id            NUMBER(19)         NOT NULL,
    from_stop          NUMBER(5)          NOT NULL,            -- the journey: stops of the trip, segments from_stop .. to_stop - 1
    to_stop            NUMBER(5)          NOT NULL,
    status             VARCHAR2(20 CHAR)  NOT NULL,
    refund_status      VARCHAR2(20 CHAR)  DEFAULT 'NONE' NOT NULL,  -- mirrored from Payment (slice 11)
    amount             NUMBER(12, 2)      NOT NULL,            -- worked out on the server from the fares of the trip
    currency           VARCHAR2(3 CHAR)   DEFAULT 'EGP' NOT NULL,
    expires_at         TIMESTAMP WITH TIME ZONE NOT NULL,      -- the hold: created_at + 5 minutes (SRS FR-H3)
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at       TIMESTAMP WITH TIME ZONE,
    cancelled_at       TIMESTAMP WITH TIME ZONE,
    cancelled_by       VARCHAR2(64 CHAR),                      -- Keycloak sub of the user or admin who cancelled (slice 11)
    cancelled_by_role  VARCHAR2(10 CHAR),                      -- USER or ADMIN
    cancel_reason      VARCHAR2(500 CHAR),                     -- only for an admin cancellation
    -- The sweeper (SRS 4.2) retries a hold whose payment is still processing, or whose Stripe call failed, at this time:
    -- a Stripe outage must not make it hammer Stripe every second.
    next_attempt_at    TIMESTAMP WITH TIME ZONE,
    attempts           NUMBER(5)          DEFAULT 0 NOT NULL,
    CONSTRAINT pk_booking PRIMARY KEY (id),
    CONSTRAINT uk_booking_reference UNIQUE (reference),
    -- A booking keeps its trip copy: a trip with bookings can never be deleted (history), which also guards the receiver.
    CONSTRAINT fk_booking_trip FOREIGN KEY (trip_id) REFERENCES trip (id),
    CONSTRAINT ck_booking_status CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'EXPIRED', 'CANCELLED', 'ABANDONED')),
    CONSTRAINT ck_booking_refund CHECK (refund_status IN ('NONE', 'REFUND_PENDING', 'REFUNDED', 'REFUND_FAILED')),
    CONSTRAINT ck_booking_role CHECK (cancelled_by_role IS NULL OR cancelled_by_role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_booking_journey CHECK (from_stop >= 0 AND to_stop > from_stop),
    CONSTRAINT ck_booking_amount CHECK (amount >= 0)
);

CREATE INDEX ix_booking_user ON booking (user_id, created_at);
CREATE INDEX ix_booking_trip_status ON booking (trip_id, status);
-- The sweeper looks for holds past their expiry.
CREATE INDEX ix_booking_due ON booking (status, expires_at);

-- What the booking contains: a seat, or places in one coach. price is the price of the whole line.
CREATE TABLE booking_item (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    booking_id  NUMBER(19)        NOT NULL,
    item_type   VARCHAR2(10 CHAR) NOT NULL,
    seat_id     NUMBER(19),                  -- for a SEAT
    coach_id    NUMBER(19),                  -- for STANDING
    qty         NUMBER(5)         DEFAULT 1 NOT NULL,
    price       NUMBER(12, 2)     NOT NULL,
    CONSTRAINT pk_booking_item PRIMARY KEY (id),
    CONSTRAINT fk_booking_item_booking FOREIGN KEY (booking_id) REFERENCES booking (id),
    CONSTRAINT ck_booking_item_type CHECK (
        (item_type = 'SEAT' AND seat_id IS NOT NULL AND coach_id IS NULL AND qty = 1)
        OR (item_type = 'STANDING' AND coach_id IS NOT NULL AND seat_id IS NULL AND qty >= 1))
);

CREATE INDEX ix_booking_item_booking ON booking_item (booking_id);

-- The standing places of a booking: which coach, which segments, how many (SRS section 5.2). The sweeper and the
-- cancellation need it to give the places back to standing_usage. The expiry is the booking's own expires_at.
CREATE TABLE standing_hold (
    booking_id    NUMBER(19) NOT NULL,
    trip_id       NUMBER(19) NOT NULL,
    coach_id      NUMBER(19) NOT NULL,
    from_segment  NUMBER(5)  NOT NULL,
    to_segment    NUMBER(5)  NOT NULL,       -- inclusive: the last segment of the journey
    qty           NUMBER(5)  NOT NULL,
    CONSTRAINT pk_standing_hold PRIMARY KEY (booking_id, coach_id),
    CONSTRAINT fk_standing_hold_booking FOREIGN KEY (booking_id) REFERENCES booking (id),
    CONSTRAINT fk_standing_hold_coach FOREIGN KEY (trip_id, coach_id) REFERENCES trip_coach (trip_id, coach_id),
    CONSTRAINT ck_standing_hold_qty CHECK (qty >= 1 AND to_segment >= from_segment)
);

-- Per-trip change counter (SRS section 6): incremented in the transaction of every change of the availability, so
-- that a client can tell whether it missed a live update. One row per trip, created with the copy of the trip.
CREATE TABLE trip_version (
    trip_id  NUMBER(19) NOT NULL,
    version  NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_trip_version PRIMARY KEY (trip_id),
    CONSTRAINT fk_trip_version_trip FOREIGN KEY (trip_id) REFERENCES trip (id) ON DELETE CASCADE
);

INSERT INTO trip_version (trip_id, version) SELECT id, 0 FROM trip;

-- The foreign key that slice 5 left for later: a reservation always belongs to a booking.
ALTER TABLE seat_reservation ADD CONSTRAINT fk_seat_reservation_booking FOREIGN KEY (booking_id) REFERENCES booking (id);
CREATE INDEX ix_seat_reservation_booking ON seat_reservation (booking_id);
