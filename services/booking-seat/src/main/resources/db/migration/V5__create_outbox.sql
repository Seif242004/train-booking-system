-- The DB outbox of Booking and Seat (CLAUDE.md, "Async calls without a broker"): the calls to Ticket and Notification that must happen
-- after a change but must never be able to fail it. A row is written in the SAME transaction as the change (the confirmation, the
-- cancellation); a @Scheduled poller delivers it with retries. A ticket or an email that cannot be made never cancels a booking.
CREATE TABLE outbox (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind             VARCHAR2(30 CHAR)  NOT NULL,
    booking_id       NUMBER(19)         NOT NULL,
    payload          CLOB,                                         -- JSON, only for the kinds that need more than the booking
    status           VARCHAR2(10 CHAR)  DEFAULT 'PENDING' NOT NULL,
    attempts         NUMBER(5)          DEFAULT 0 NOT NULL,
    next_attempt_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error       VARCHAR2(500 CHAR),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_outbox PRIMARY KEY (id),
    CONSTRAINT fk_outbox_booking FOREIGN KEY (booking_id) REFERENCES booking (id),
    CONSTRAINT ck_outbox_kind CHECK (kind IN ('TICKET_EMAIL', 'TICKET_INVALIDATE', 'CANCELLATION_EMAIL', 'REFUND_EMAIL')),
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX ix_outbox_due ON outbox (status, next_attempt_at);
CREATE INDEX ix_outbox_booking ON outbox (booking_id, status);
