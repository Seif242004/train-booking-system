-- Notification schema, first migration: the emails to send (a DB outbox with retries) and the audit log. Runs as the notification user.

-- Every email the system sends. A row is written when another service asks for an email (and the caller gets its answer at once), and
-- a poller sends it by SMTP with retries: an email that cannot be sent never affects the booking it is about (CLAUDE.md).
CREATE TABLE email (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dedupe_key       VARCHAR2(100 CHAR) NOT NULL,                  -- chosen by the caller: asking twice for the same email stores one
    kind             VARCHAR2(20 CHAR)  NOT NULL,                  -- TICKET, CANCELLATION or REFUND
    booking_ref      VARCHAR2(20 CHAR)  NOT NULL,
    recipient        VARCHAR2(320 CHAR) NOT NULL,
    recipient_name   VARCHAR2(200 CHAR),
    subject          VARCHAR2(300 CHAR) NOT NULL,
    body_text        CLOB               NOT NULL,
    body_html        CLOB               NOT NULL,
    attachment_name  VARCHAR2(200 CHAR),
    attachment_type  VARCHAR2(100 CHAR),
    attachment       BLOB,
    status           VARCHAR2(10 CHAR)  DEFAULT 'PENDING' NOT NULL,
    attempts         NUMBER(5)          DEFAULT 0 NOT NULL,
    next_attempt_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error       VARCHAR2(500 CHAR),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_email PRIMARY KEY (id),
    CONSTRAINT uk_email_dedupe UNIQUE (dedupe_key),
    CONSTRAINT ck_email_kind CHECK (kind IN ('TICKET', 'CANCELLATION', 'REFUND')),
    CONSTRAINT ck_email_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX ix_email_due ON email (status, next_attempt_at);

CREATE TABLE audit_log (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    admin_id    VARCHAR2(64 CHAR) NOT NULL,   -- who caused it: the calling service
    entity      VARCHAR2(50 CHAR) NOT NULL,
    entity_id   NUMBER(19)        NOT NULL,
    action      VARCHAR2(30 CHAR) NOT NULL,
    diff        CLOB,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (id)
);
