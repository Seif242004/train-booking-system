-- Payment schema, first migration (SRS section 8: payment, refund, webhook_event; plus the outbox and the audit log).
-- Runs as the payment user, so the tables land in that schema.

-- One payment per booking. The row is created BEFORE Stripe is asked (status CREATING), so that cancelling a payment that is still
-- being created has something to mark: a CANCELLED row without an intent is a tombstone that refuses a late creation (SRS 4.2).
CREATE TABLE payment (
    id                        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    booking_id                NUMBER(19)         NOT NULL,         -- the id in Booking and Seat, a plain value
    stripe_payment_intent_id  VARCHAR2(100 CHAR),
    status                    VARCHAR2(20 CHAR)  NOT NULL,
    amount                    NUMBER(12, 2)      NOT NULL,
    currency                  VARCHAR2(3 CHAR)   NOT NULL,
    last_error                VARCHAR2(500 CHAR),                  -- the last failed attempt of the user (the intent stays open)
    revision                  NUMBER(5)          DEFAULT 1 NOT NULL, -- 1, then 2... each time the payment was invalidated and made again: part of the Stripe idempotency key
    ended                     NUMBER(1)          DEFAULT 0 NOT NULL, -- 1 once the hold of the booking ended: no payment may be created for it any more
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_payment PRIMARY KEY (id),
    CONSTRAINT uk_payment_booking UNIQUE (booking_id),
    CONSTRAINT uk_payment_intent UNIQUE (stripe_payment_intent_id),
    CONSTRAINT ck_payment_status CHECK (status IN ('CREATING', 'PENDING', 'PROCESSING', 'SUCCEEDED', 'CANCELLED')),
    CONSTRAINT ck_payment_amount CHECK (amount >= 0)
);

-- A full refund of a payment (there are no partial refunds). The row is created first and its id is the idempotency key of the
-- Stripe call, so a retry can never refund twice.
CREATE TABLE refund (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    booking_id        NUMBER(19)         NOT NULL,
    payment_id        NUMBER(19)         NOT NULL,
    stripe_refund_id  VARCHAR2(100 CHAR),
    amount            NUMBER(12, 2)      NOT NULL,
    status            VARCHAR2(20 CHAR)  NOT NULL,
    reason            VARCHAR2(500 CHAR),
    failure_reason    VARCHAR2(500 CHAR),
    attempts          NUMBER(5)          DEFAULT 0 NOT NULL,
    next_attempt_at   TIMESTAMP WITH TIME ZONE,                    -- when Stripe could not be reached: the next try
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_refund PRIMARY KEY (id),
    CONSTRAINT uk_refund_booking UNIQUE (booking_id),
    CONSTRAINT uk_refund_stripe UNIQUE (stripe_refund_id),
    CONSTRAINT fk_refund_payment FOREIGN KEY (payment_id) REFERENCES payment (id),
    CONSTRAINT ck_refund_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED'))
);

-- Every Stripe event is handled at most once (FR-P6): its id is the primary key, so a second delivery cannot insert it.
CREATE TABLE webhook_event (
    stripe_event_id  VARCHAR2(100 CHAR) NOT NULL,
    event_type       VARCHAR2(100 CHAR) NOT NULL,
    processed_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_webhook_event PRIMARY KEY (stripe_event_id)
);

-- The news for Booking and Seat (a payment succeeded, a refund changed), written in the same transaction as the change that
-- causes it and delivered by a retrying poller: a Booking that is down never loses a payment (CLAUDE.md, "Async calls without a broker").
CREATE TABLE outbox (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind             VARCHAR2(40 CHAR)  NOT NULL,                   -- PAYMENT_RESULT or REFUND_STATUS
    booking_id       NUMBER(19)         NOT NULL,
    payload          CLOB               NOT NULL,                   -- JSON
    status           VARCHAR2(10 CHAR)  DEFAULT 'PENDING' NOT NULL,
    attempts         NUMBER(5)          DEFAULT 0 NOT NULL,
    next_attempt_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error       VARCHAR2(500 CHAR),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_outbox PRIMARY KEY (id),
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX ix_outbox_due ON outbox (status, next_attempt_at);

CREATE TABLE audit_log (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    admin_id    VARCHAR2(64 CHAR) NOT NULL,   -- who caused it: the caller of the internal API, or "stripe" for a webhook
    entity      VARCHAR2(50 CHAR) NOT NULL,
    entity_id   NUMBER(19)        NOT NULL,
    action      VARCHAR2(30 CHAR) NOT NULL,
    diff        CLOB,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (id)
);
