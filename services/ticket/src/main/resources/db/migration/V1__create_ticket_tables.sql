-- Ticket schema, first migration (SRS section 8: ticket; plus the audit log). Runs as the ticket user.

-- One PDF ticket per booking, with all its seats and standing places. The row is created when the booking is confirmed and is never
-- deleted: a cancelled booking's ticket is INVALIDATED (its QR token no longer valid), the PDF is kept as the record.
CREATE TABLE ticket (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    booking_id      NUMBER(19)         NOT NULL,                  -- the id in Booking and Seat, a plain value
    reference       VARCHAR2(20 CHAR)  NOT NULL,                  -- the booking reference printed on the ticket
    qr_token        VARCHAR2(200 CHAR) NOT NULL,                  -- reference.nonce.signature: what the QR code carries
    status          VARCHAR2(12 CHAR)  NOT NULL,
    pdf             BLOB               NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    invalidated_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_ticket PRIMARY KEY (id),
    CONSTRAINT uk_ticket_booking UNIQUE (booking_id),             -- one ticket per booking: a repeated request returns it
    CONSTRAINT uk_ticket_token UNIQUE (qr_token),
    CONSTRAINT ck_ticket_status CHECK (status IN ('VALID', 'INVALIDATED'))
);

CREATE TABLE audit_log (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    admin_id    VARCHAR2(64 CHAR) NOT NULL,   -- who caused it: the calling service
    entity      VARCHAR2(50 CHAR) NOT NULL,
    entity_id   NUMBER(19)        NOT NULL,
    action      VARCHAR2(30 CHAR) NOT NULL,
    diff        CLOB,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (id)
);
