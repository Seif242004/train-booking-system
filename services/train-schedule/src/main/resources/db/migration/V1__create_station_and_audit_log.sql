-- Train & Schedule schema, first migration. Runs as the train_schedule user, so the tables land in that schema.

-- SRS section 8: station(id, code, name, city).
CREATE TABLE station (
    id    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code  VARCHAR2(10 CHAR)  NOT NULL,
    name  VARCHAR2(100 CHAR) NOT NULL,
    city  VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT pk_station PRIMARY KEY (id),
    -- The database, not the application, guarantees that a station code is unique (ORA-00001 on a duplicate).
    CONSTRAINT uk_station_code UNIQUE (code)
);

-- SRS section 8 and FR-A10: every admin create, update and delete is written to an audit log.
CREATE TABLE audit_log (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    admin_id    VARCHAR2(64 CHAR) NOT NULL,   -- the admin's Keycloak user id (JWT sub), a plain value
    entity      VARCHAR2(50 CHAR) NOT NULL,   -- for example 'station'
    entity_id   NUMBER(19)        NOT NULL,
    action      VARCHAR2(20 CHAR) NOT NULL,   -- CREATE, UPDATE or DELETE
    diff        CLOB,                         -- JSON: the values before and after the change
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (id)
);
