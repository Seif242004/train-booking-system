-- Slice 2: trains, coaches, seats and standing capacity (SRS section 8, FR-A1 to FR-A7).
--
-- Three SRS column names are Oracle reserved words and cannot be used as plain column names. They are renamed in the
-- database only; the JSON API keeps the SRS names exactly (number, row, column):
--   train.number -> train_number    (NUMBER is a reserved word)
--   seat.row     -> seat_row        (ROW is a reserved word)
--   seat.column  -> seat_column     (COLUMN is a reserved word)

CREATE TABLE train (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    train_number  VARCHAR2(20 CHAR)  NOT NULL,   -- SRS: train.number, unique (see the note above)
    name          VARCHAR2(100 CHAR) NOT NULL,
    type          VARCHAR2(50 CHAR)  NOT NULL,   -- free text, for example 'Express'
    status        VARCHAR2(10 CHAR)  NOT NULL,   -- ACTIVE or INACTIVE
    CONSTRAINT pk_train PRIMARY KEY (id),
    CONSTRAINT uk_train_number UNIQUE (train_number),
    CONSTRAINT ck_train_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE coach (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    train_id           NUMBER(19)        NOT NULL,
    code               VARCHAR2(10 CHAR) NOT NULL,
    class              VARCHAR2(10 CHAR) NOT NULL,   -- FIRST, SECOND or THIRD (our decision: the SRS gives no values)
    position           NUMBER(5)         NOT NULL,   -- order of the coach in the train, starting at 1 (FR-A5)
    standing_capacity  NUMBER(10) DEFAULT 0 NOT NULL, -- standing places in this coach, 0 or more (FR-A7)
    CONSTRAINT pk_coach PRIMARY KEY (id),
    -- Deleting a train deletes its coaches (and, through seat below, their seats).
    -- TODO(FR-A4, Flow 7): refuse the delete when the train has future trips with confirmed bookings, once trips exist.
    CONSTRAINT fk_coach_train FOREIGN KEY (train_id) REFERENCES train (id) ON DELETE CASCADE,
    CONSTRAINT uk_coach_code UNIQUE (train_id, code),
    CONSTRAINT uk_coach_position UNIQUE (train_id, position),
    CONSTRAINT ck_coach_class CHECK (class IN ('FIRST', 'SECOND', 'THIRD')),
    CONSTRAINT ck_coach_position CHECK (position >= 1),
    CONSTRAINT ck_coach_standing CHECK (standing_capacity >= 0)
);

CREATE TABLE seat (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    coach_id     NUMBER(19)        NOT NULL,
    seat_number  VARCHAR2(10 CHAR) NOT NULL,
    seat_row     NUMBER(5)         NOT NULL,   -- SRS: seat.row (see the note above); 1 or more
    seat_column  VARCHAR2(3 CHAR)  NOT NULL,   -- SRS: seat.column (see the note above); letters, for example 'A'
    class        VARCHAR2(10 CHAR) NOT NULL,   -- always equals the coach's class: set by the server, never by the client
    CONSTRAINT pk_seat PRIMARY KEY (id),
    CONSTRAINT fk_seat_coach FOREIGN KEY (coach_id) REFERENCES coach (id) ON DELETE CASCADE,
    CONSTRAINT uk_seat_number UNIQUE (coach_id, seat_number),
    CONSTRAINT uk_seat_position UNIQUE (coach_id, seat_row, seat_column),
    CONSTRAINT ck_seat_class CHECK (class IN ('FIRST', 'SECOND', 'THIRD')),
    CONSTRAINT ck_seat_row CHECK (seat_row >= 1)
);
