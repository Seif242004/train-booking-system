-- Slice 3: routes with ordered stops, and fares per route segment per coach class (SRS section 8, FR-A8, 9.2).
-- A route visits stations in order. Segment k is the leg from stop k to stop k+1, so a route with n stops has n-1 segments.
-- None of the SRS column names here is an Oracle reserved word, so they are used as written.

CREATE TABLE route (
    id    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name  VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT pk_route PRIMARY KEY (id)
);

CREATE TABLE route_stop (
    route_id    NUMBER(19) NOT NULL,
    stop_index  NUMBER(5)  NOT NULL,   -- 0 for the first stop, counting up in travel order
    station_id  NUMBER(19) NOT NULL,
    CONSTRAINT pk_route_stop PRIMARY KEY (route_id, stop_index),
    -- Deleting a route deletes its stops (and, through fare below, its fares).
    -- TODO(slice 4): refuse deleting a route that trips use.
    CONSTRAINT fk_route_stop_route FOREIGN KEY (route_id) REFERENCES route (id) ON DELETE CASCADE,
    -- No cascade here: a station that a route uses cannot be deleted (the service answers 409 station_in_use).
    CONSTRAINT fk_route_stop_station FOREIGN KEY (station_id) REFERENCES station (id),
    -- A route visits each station at most once.
    CONSTRAINT uk_route_stop_station UNIQUE (route_id, station_id),
    CONSTRAINT ck_route_stop_index CHECK (stop_index >= 0)
);

-- Oracle recommends an index on a foreign key column: it speeds up the "is this station in use" check on a delete.
CREATE INDEX ix_route_stop_station ON route_stop (station_id);

CREATE TABLE fare (
    route_id       NUMBER(19)        NOT NULL,
    segment_index  NUMBER(5)         NOT NULL,   -- 0 is the leg from stop 0 to stop 1
    coach_class    VARCHAR2(10 CHAR) NOT NULL,   -- FIRST, SECOND or THIRD, as for coaches
    amount         NUMBER(10, 2)     NOT NULL,   -- price of this segment for this class, in the currency below
    currency       VARCHAR2(3 CHAR) DEFAULT 'EGP' NOT NULL,
    CONSTRAINT pk_fare PRIMARY KEY (route_id, segment_index, coach_class),
    CONSTRAINT fk_fare_route FOREIGN KEY (route_id) REFERENCES route (id) ON DELETE CASCADE,
    CONSTRAINT ck_fare_class CHECK (coach_class IN ('FIRST', 'SECOND', 'THIRD')),
    CONSTRAINT ck_fare_segment CHECK (segment_index >= 0),
    CONSTRAINT ck_fare_amount CHECK (amount > 0),
    CONSTRAINT ck_fare_currency CHECK (currency = 'EGP')   -- fares are in Egyptian pounds only (CLAUDE.md, "Fares")
);
