-- Slice 4: scheduled trips of a train on a route, with the time at every stop (SRS section 8, FR-A8, 9.2).
-- None of the SRS column names here is an Oracle reserved word, so they are used as written.

CREATE TABLE trip (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    train_id        NUMBER(19) NOT NULL,
    route_id        NUMBER(19) NOT NULL,
    departure_date  DATE       NOT NULL,   -- the date the trip leaves its first stop, in the service time zone
    status          VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL,   -- CANCELLED is set by the whole-trip cancel (slice 12)
    CONSTRAINT pk_trip PRIMARY KEY (id),
    -- No cascade: a train or a route that trips use cannot be deleted (the service answers 409 train_in_use or route_in_use).
    CONSTRAINT fk_trip_train FOREIGN KEY (train_id) REFERENCES train (id),
    CONSTRAINT fk_trip_route FOREIGN KEY (route_id) REFERENCES route (id),
    CONSTRAINT ck_trip_status CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

CREATE INDEX ix_trip_train ON trip (train_id);
CREATE INDEX ix_trip_route ON trip (route_id);

CREATE TABLE trip_stop (
    trip_id         NUMBER(19) NOT NULL,
    stop_index      NUMBER(5)  NOT NULL,   -- the same numbering as the route's stops: 0 is the first stop
    station_id      NUMBER(19) NOT NULL,   -- copied from the route when the trip is saved
    arrival_time    TIMESTAMP WITH TIME ZONE,   -- empty at the first stop
    departure_time  TIMESTAMP WITH TIME ZONE,   -- empty at the last stop
    CONSTRAINT pk_trip_stop PRIMARY KEY (trip_id, stop_index),
    -- Deleting a trip deletes its stops.
    -- TODO(slice 5): refuse deleting a trip that has holds or confirmed bookings (cancel it instead, Flow 8).
    CONSTRAINT fk_trip_stop_trip FOREIGN KEY (trip_id) REFERENCES trip (id) ON DELETE CASCADE,
    CONSTRAINT fk_trip_stop_station FOREIGN KEY (station_id) REFERENCES station (id),
    CONSTRAINT ck_trip_stop_time CHECK (arrival_time IS NOT NULL OR departure_time IS NOT NULL)
);

-- Trip search looks up a station and a departure time window.
CREATE INDEX ix_trip_stop_station ON trip_stop (station_id, departure_time);
